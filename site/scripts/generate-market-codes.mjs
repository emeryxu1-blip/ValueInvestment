#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const skillRoot = resolve(projectRoot, "../skills/ainvest-marketcode/references");
const securityPath = resolve(skillRoot, "security_config_V1.1.csv");
const namesPath = resolve(skillRoot, "ainvest_market_code_names_en.csv");
const outputPath = resolve(projectRoot, "data/market-codes.generated.mjs");
const declarationPath = resolve(projectRoot, "data/market-codes.generated.d.mts");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        field += character;
      }
    } else if (character === '"') {
      quoted = true;
    } else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += character;
    }
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field.replace(/\r$/, ""));
    rows.push(row);
  }
  return rows;
}

function asRecords(rows) {
  const [headers, ...values] = rows;
  return values
    .filter((row) => row.some(Boolean))
    .map((row) => Object.fromEntries(headers.map((header, index) => [header, row[index] ?? ""])));
}

function exchangeFor(record) {
  const [market] = record.key.split(":", 1);
  if (market === "185" || market === "186") return "nasdaq";
  if (market === "170") return "amex";
  if (market === "171") return "cboe";
  if (market === "169") return record.listing_market === "P" ? "arca" : "nyse";
  return null;
}

const [securityText, namesText] = await Promise.all([
  readFile(securityPath, "utf8"),
  readFile(namesPath, "utf8"),
]);
const securities = asRecords(parseCsv(securityText.replace(/^\uFEFF/, "")));
const names = new Map(
  asRecords(parseCsv(namesText.replace(/^\uFEFF/, ""))).map((row) => [
    row.market_code,
    row.security_name,
  ]),
);

const routeEntries = [];
const bySymbol = new Map();
for (const record of securities) {
  const exchange = exchangeFor(record);
  if (!exchange) continue;
  const separator = record.key.indexOf(":");
  const symbol = record.key.slice(separator + 1).toUpperCase();
  const routeKey = `${exchange}:${symbol}`;
  const value = [
    record.key,
    names.get(record.key) || symbol,
    record.security_type,
  ];
  routeEntries.push([routeKey, value]);
  const routes = bySymbol.get(symbol) ?? new Set();
  routes.add(routeKey);
  bySymbol.set(symbol, routes);
}
routeEntries.sort(([left], [right]) => left.localeCompare(right));

const generatedAt = new Date().toISOString();
const symbolRoutes = Object.fromEntries(
  [...bySymbol.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([symbol, routes]) => [symbol, [...routes].sort()]),
);
const output = `// Generated by scripts/generate-market-codes.mjs from the June 9, 2026\n// ainvest-marketcode catalog. Do not edit by hand.\n\nexport const MARKET_CODE_CATALOG_AS_OF = "2026-06-09";\nexport const MARKET_CODE_CATALOG_GENERATED_AT = ${JSON.stringify(generatedAt)};\n\nexport const MARKET_CODE_BY_ROUTE = ${JSON.stringify(Object.fromEntries(routeEntries))};\n\nexport const ROUTES_BY_SYMBOL = ${JSON.stringify(symbolRoutes)};\n`;

const declaration = `export type GeneratedMarketCodeEntry = readonly [\n  marketCode: string,\n  companyName: string,\n  securityType: string,\n];\nexport const MARKET_CODE_CATALOG_AS_OF: string;\nexport const MARKET_CODE_CATALOG_GENERATED_AT: string;\nexport const MARKET_CODE_BY_ROUTE: Readonly<Record<string, GeneratedMarketCodeEntry>>;\nexport const ROUTES_BY_SYMBOL: Readonly<Record<string, readonly string[]>>;\n`;

await Promise.all([
  writeFile(outputPath, output, "utf8"),
  writeFile(declarationPath, declaration, "utf8"),
]);
console.log(`Generated ${routeEntries.length} route entries in ${outputPath}`);
